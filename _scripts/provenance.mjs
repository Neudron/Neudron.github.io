#!/usr/bin/env node
/* provenance.mjs — regenerate the sprite provenance table (ultraplan M4).
   Reads the live NEU.sheets manifest from js/data/sheets.js (evaluated in
   a stub window, not regex-scraped) and writes one row per sheet — key,
   file, frame geometry, and the `from:` source path when the entry cites
   one — into memory/assets.md between the provenance markers. Running it
   twice produces no diff.  node _scripts/provenance.mjs [--check]        */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const win = { NEU: {}, document: { createElement: () => ({}) }, Image: function () {} };
new Function('window', 'document', 'Image', fs.readFileSync(path.join(ROOT, 'js/data/sheets.js'), 'utf8'))(win, win.document, win.Image);
const sheets = win.NEU.sheets || {};
const rows = Object.keys(sheets).sort().map(k => {
  const s = sheets[k];
  const file = String(s.src || '').replace(/^.*?img\//, 'img/');
  const exists = fs.existsSync(path.join(ROOT, file));
  return `| \`${k}\` | \`${file}\`${exists ? '' : ' ⚠ missing'} | ${s.fw || '?'}×${s.fh || '?'} × ${s.frames || 1}${s.cols ? ' (' + s.cols + ' cols)' : ''} | ${s.from ? '`' + s.from + '`' : '—'} |`;
});
const table = ['<!-- provenance:start (generated by _scripts/provenance.mjs — do not edit by hand) -->',
  '| sheet | file | frame × frames | cited source |', '|---|---|---|---|', ...rows,
  `<!-- provenance:end — ${rows.length} sheets, ${Object.values(sheets).filter(s => s.from).length} with a cited source -->`].join('\n');
const P = path.join(ROOT, 'memory/assets.md');
let doc = fs.readFileSync(P, 'utf8');
const re = /<!-- provenance:start[\s\S]*?<!-- provenance:end[^>]*-->/;
const next = re.test(doc) ? doc.replace(re, table) : doc.trimEnd() + '\n\n## Sprite provenance (generated)\n\n' + table + '\n';
if (process.argv.includes('--check')) { console.log(next === doc ? 'provenance table is current' : 'provenance table is STALE'); process.exit(next === doc ? 0 : 1); }
fs.writeFileSync(P, next);
console.log('wrote ' + rows.length + ' rows to memory/assets.md');
